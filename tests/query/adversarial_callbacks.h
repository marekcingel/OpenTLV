static tlv_visit_result_t document_visitor(tlv_node_t*, void*);
static void               mutate(callback_state* s) {
    if (!s->document) return;
    tlv_node_t*   node = s->node;
    tlv_node_t*   parent = tlv_node_parent(node);
    const uint8_t tag = 1, value = 8;
    uint64_t      identity = tlv_node_identity(node);
    switch (s->mutation) {
        case 1: tlv_node_erase(node); break;
        case 2: tlv_node_erase(parent ? parent : node); break;
        case 3:
        case 4:
            if (tlv_node_set_value(s->mutation == 4 && parent ? parent : node, &value, 1) !=
                TLV_ERR_INVALID_STATE)
                ++s->errors;
            break;
        case 5:
        case 6:
            if (tlv_document_insert(s->document, parent,
                                    s->mutation == 5 ? node : tlv_node_next(node), tlv_tag(&tag, 1),
                                    &value, 1, NULL) != TLV_ERR_INVALID_STATE)
                ++s->errors;
            break;
        case 7:
            if (tlv_document_query_program_visit(s->exec, document_visitor, s) !=
                TLV_ERR_INVALID_STATE)
                ++s->errors;
            break;
        case 8: tlv_document_free(s->document); break;
        case 9:
            tlv_node_erase(node);
            tlv_node_erase(parent ? parent : node);
            break;
    }
    /* Erase/free are deferred: borrowed node/tag/value survive this callback. */
    if (tlv_node_identity(node) != identity || tlv_node_tag(node).size != 1) ++s->errors;
}
static tlv_visit_result_t document_visitor(tlv_node_t* node, void* context) {
    callback_state* s = context;
    s->node = node;
    reenter(s);
    mutate(s);
    return TLV_VISIT_STOP;
}
