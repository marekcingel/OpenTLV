static int callbacks(void) {
    tlv_fixed_format_t config = {
        {0}, {0, TLV_BYTE_ORDER_UNKNOWN}, TLV_ELEMENT_ORDER_TLV, TLV_LENGTH_SCOPE_VALUE};
    config.identifier.size = config.length.size = 1;
    config.length.byte_order = TLV_BYTE_ORDER_BIG_ENDIAN;
    tlv_format_t format;
    CHECK(tlv_fixed_format_init(&format, &config) == TLV_OK);
    callback_state          state = {0};
    tlv_query_hook_t        hook = {73, TLV_QUERY_NUM, 0, 1, &state, decode};
    tlv_query_tag_adapter_t tags = {74, &state, tag_number, tag_number};
    tlv_query_environment_t environment = {0};
    environment.hooks = &hook;
    environment.hook_count = 1;
    environment.tags = &tags;
    arena                      image, memory;
    const tlv_query_program_t* p;
    const char*                expressions[] = {"num(//01)", "number(//01)", "class(//01)"};
    for (unsigned kind = 0; kind < 3; ++kind) {
        CHECK(compile_plan(expressions[kind], &environment, &image, &p) == 0);
        size_t bytes, alignment;
        CHECK(tlv_query_eval_size(p, 2, 3, &bytes, &alignment) == TLV_OK);
        CHECK(tlv_query_eval_init(p, &environment, aligned(&memory), bytes, 2, 3, 100000,
                                  &state.exec) == TLV_OK);
        for (int failed = 1; failed >= 0; --failed) {
            state.fail = failed;
            state.calls = state.errors = 0;
            CHECK(tlv_query_exec_reset(state.exec) == TLV_OK);
            tlv_tree_event_t input = event();
            int              matched;
            CHECK(tlv_query_exec_feed(state.exec, &input, &matched, NULL) == TLV_OK);
            tlv_result_t rc = tlv_query_exec_finish(state.exec, NULL);
            CHECK(failed ? rc != TLV_OK : rc == TLV_OK);
            CHECK(state.calls && !state.errors);
            tlv_query_result_t result;
            CHECK(tlv_query_exec_result(state.exec, &result) ==
                  (failed ? TLV_ERR_INVALID_STATE : TLV_OK));
            if (!failed) CHECK(result.integer == 1);
        }
    }
#if OPENTLV_READER
    format.is_constructed = constructed;
    const char* selections[] = {"//01", "/70[child::01]"};
    for (unsigned kind = 0; kind < 2; ++kind)
        for (int retained = 0; retained < 2; ++retained) {
            CHECK(compile_plan(selections[kind], NULL, &image, &p) == 0);
            size_t bytes, alignment;
            CHECK((retained ? tlv_query_eval_size(p, 2, 4, &bytes, &alignment)
                            : tlv_query_exec_size(p, 2, &bytes, &alignment)) == TLV_OK);
            CHECK((retained ? tlv_query_eval_init(p, NULL, aligned(&memory), bytes, 2, 4, 100000,
                                                  &state.exec)
                            : tlv_query_exec_init(p, aligned(&memory), bytes, 2, 4, 100000,
                                                  &state.exec)) == TLV_OK);
            state.workspace_bytes = bytes;
            const uint8_t     wire[] = {0x70, 2, 1, 0, 0x70, 2, 1, 0};
            tlv_tree_reader_t reader;
            tlv_tree_frame_t  frames[4];
            CHECK(tlv_tree_reader_init(&reader, wire, sizeof wire, &format, frames, 4, 3, 4) ==
                  TLV_OK);
            state.calls = state.errors = 0;
            CHECK(tlv_query_program_visit(&reader, state.exec, event_visitor, &state, NULL) ==
                  TLV_OK);
            CHECK(state.calls == 2 && !state.errors);
        }
#endif
    return 0;
}
typedef struct raw_init_state {
    const tlv_query_program_t*     program;
    const tlv_query_environment_t* environment;
    tlv_query_exec_t*              exec;
    size_t                         bytes;
    int                            retained, calls;
    tlv_result_t                   status;
} raw_init_state;
static void raw_reinitialize(raw_init_state* s) {
    ++s->calls;
    s->status = s->retained
                    ? tlv_query_eval_init(s->program, s->environment, s->exec, s->bytes, 2, 4,
                                          100000, &s->exec)
                    : tlv_query_exec_init(s->program, s->exec, s->bytes, 2, 4, 100000, &s->exec);
}
static tlv_result_t reinitializing_tag(const void* context, const tlv_tag_t* tag, int64_t* out) {
    (void)tag;
    raw_reinitialize((raw_init_state*)context);
    *out = 1;
    return TLV_OK;
}
static int reinitializing_constructed(const void* context, const tlv_tag_t* tag) {
    (void)tag;
    raw_reinitialize((raw_init_state*)context);
    return 0;
}
static tlv_codec_result_t reinitializing_codec(const void* context, const tlv_tree_event_t* input,
                                               const uint8_t* data, size_t size, void* scratch,
                                               size_t capacity, tlv_query_result_t* out) {
    (void)input;
    (void)data;
    (void)size;
    (void)scratch;
    (void)capacity;
    raw_reinitialize((raw_init_state*)context);
    out->kind = TLV_QUERY_RESULT_INTEGER;
    out->integer = 1;
    return TLV_CODEC_OK;
}
