static int constructed(const void* context, const tlv_tag_t* tag) {
    (void)context;
    return tag->size == 1 && tag->data[0] == 0x70;
}
static int documents(void) {
    const char*        expressions[] = {"//01",           "/70[child::01]",
                                        "(//01)[last()]", "//01 | //01/following::*",
                                        "num(//01[1])",   "number(//01[1])"};
    tlv_fixed_format_t config = {0};
    config.tag_size = config.length_size = 1;
    config.length_order = TLV_BYTE_ORDER_BIG_ENDIAN;
    tlv_format_t format;
    CHECK(tlv_fixed_format_init(&format, &config) == TLV_OK);
    format.is_constructed = constructed;
    tlv_document_options_t options;
    CHECK(tlv_document_options_init(&options, &format) == TLV_OK);
    options.retain_source_locations = 1;
    for (unsigned kind = 0; kind < 6; ++kind)
        for (int mutation = 0; mutation <= 9; ++mutation) {
            const uint8_t  wire[] = {0x70, 3, 1, 1, 9};
            callback_state state = {0};
            state.mutation = mutation;
            CHECK(tlv_document_parse(wire, sizeof wire, &options, &state.document, NULL) == TLV_OK);
            state.node = tlv_node_first_child(tlv_document_first(state.document));
            tlv_query_hook_t        hook = {73, TLV_QUERY_NUM, 0, 1, &state, decode};
            tlv_query_tag_adapter_t tags = {74, &state, tag_number, tag_number};
            tlv_query_environment_t environment = {0};
            environment.format = &format;
            environment.hooks = &hook;
            environment.hook_count = 1;
            environment.tags = &tags;
            arena                      image, memory;
            const tlv_query_program_t* p;
            CHECK(compile_plan(expressions[kind], &environment, &image, &p) == 0);
            size_t bytes, alignment;
            CHECK(tlv_query_eval_size(p, 3, 8, &bytes, &alignment) == TLV_OK);
            CHECK(tlv_query_eval_init(p, &environment, aligned(&memory), bytes, 3, 8, 100000,
                                      &state.exec) == TLV_OK);
            uint8_t                     values[64], scratch[64];
            tlv_tree_writer_frame_t     frames[8];
            tlv_tree_writer_workspace_t staging = {0};
            staging.data = values;
            staging.data_capacity = sizeof values;
            staging.scratch = scratch;
            staging.scratch_capacity = sizeof scratch;
            staging.frames = frames;
            staging.frame_capacity = 8;
            tlv_result_t rc = tlv_document_query_evaluate(state.document, state.exec, NULL, values,
                                                          sizeof values, &staging, NULL);
            if (kind < 4) {
                CHECK(rc == TLV_OK);
                rc = tlv_document_query_program_visit(state.exec, document_visitor, &state);
            }
            int invalid = mutation == 1 || mutation == 2 || mutation == 8 || mutation == 9;
            CHECK(rc == (invalid ? TLV_ERR_INVALID_ARG : TLV_OK));
            CHECK(state.calls && !state.errors);
            if (invalid) {
                tlv_query_result_t output;
                tlv_node_t*        node = NULL;
                CHECK(tlv_query_exec_result(state.exec, &output) == TLV_ERR_INVALID_ARG);
                CHECK(tlv_document_query_next(state.exec, &node) == TLV_ERR_INVALID_ARG);
            }
            CHECK(tlv_query_exec_reset(state.exec) == TLV_OK);
            if (mutation != 8) tlv_document_free(state.document);
        }
    return 0;
}
