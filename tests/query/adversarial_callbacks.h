static tlv_codec_result_t decode(const void* context, const tlv_tree_event_t* input,
                                 const uint8_t* data, size_t size, void* scratch, size_t capacity,
                                 tlv_query_result_t* out) {
    callback_state* s = (callback_state*)context;
    (void)input;
    (void)data;
    (void)size;
    (void)scratch;
    (void)capacity;
    reenter(s);
    mutate(s);
    /* Resolver runs at compile time. Nested independent compilation is supported,
     * but operations on the surrounding active execution still must be rejected. */
    arena                       image, workspace;
    tlv_query_environment_t     environment = {0};
    tlv_query_compile_options_t options;
    tlv_query_compile_options_init(&options);
    options.environment = &environment;
    options.resolve = resolve;
    options.resolve_context = s;
    tlv_query_program_info_t info = {0};
    info.struct_size = sizeof info;
    tlv_result_t rc =
        tlv_query_compile("//named", 7, &options, aligned(&workspace), sizeof workspace.bytes - 16,
                          aligned(&image), sizeof image.bytes - 16, &info, NULL);
    if ((s->fail && rc == TLV_OK) || (!s->fail && rc != TLV_OK)) ++s->errors;
    out->kind = TLV_QUERY_RESULT_INTEGER;
    out->integer = 1;
    return s->fail ? TLV_CODEC_ERR_INVALID_VALUE : TLV_CODEC_OK;
}
static tlv_result_t tag_number(const void* context, const tlv_tag_t* tag, int64_t* out) {
    callback_state* s = (callback_state*)context;
    reenter(s);
    mutate(s);
    *out = tag->data[0];
    return s->fail ? TLV_ERR_INVALID_TAG : TLV_OK;
}
