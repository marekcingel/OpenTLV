static int callbacks(void) {
    tlv_fixed_format_t config = {0};
    config.tag_size = config.length_size = 1;
    config.length_order = TLV_BYTE_ORDER_BIG_ENDIAN;
    tlv_format_t format;
    CHECK(tlv_fixed_format_init(&format, &config) == TLV_OK);
    callback_state          state = {0};
    tlv_query_hook_t        hook = {73, TLV_QUERY_NUM, 0, 1, &state, decode};
    tlv_query_tag_adapter_t tags = {74, &state, tag_number, tag_number};
    tlv_query_environment_t environment = {0};
    environment.hooks = &hook;
    environment.hook_count = 1;
    environment.tags = &tags;
    arena                      image, memory;
    const tlv_query_program_t* p;
    const char*                expressions[] = {"num(//01)", "number(//01)", "class(//01)"};
    for (unsigned kind = 0; kind < 3; ++kind) {
        CHECK(compile_plan(expressions[kind], &environment, &image, &p) == 0);
        size_t bytes, alignment;
        CHECK(tlv_query_eval_size(p, 2, 3, &bytes, &alignment) == TLV_OK);
        CHECK(tlv_query_eval_init(p, &environment, aligned(&memory), bytes, 2, 3, 100000,
                                  &state.exec) == TLV_OK);
        for (int failed = 1; failed >= 0; --failed) {
            state.fail = failed;
            state.calls = state.errors = 0;
            CHECK(tlv_query_exec_reset(state.exec) == TLV_OK);
            tlv_tree_event_t input = event();
            int              matched;
            CHECK(tlv_query_exec_feed(state.exec, &input, &matched, NULL) == TLV_OK);
            tlv_result_t rc = tlv_query_exec_finish(state.exec, NULL);
            CHECK(failed ? rc != TLV_OK : rc == TLV_OK);
            CHECK(state.calls && !state.errors);
            tlv_query_result_t result;
            CHECK(tlv_query_exec_result(state.exec, &result) ==
                  (failed ? TLV_ERR_INVALID_ARG : TLV_OK));
            if (!failed) CHECK(result.integer == 1);
        }
    }
#if OPENTLV_READER
    CHECK(compile_plan("//01", NULL, &image, &p) == 0);
    for (int retained = 0; retained < 2; ++retained) {
        size_t bytes;
        CHECK(initialize(p, retained, &memory, &state.exec, &bytes) == 0);
        const uint8_t     wire[] = {1, 0, 1, 0};
        tlv_tree_reader_t reader;
        tlv_tree_frame_t  frames[4];
        CHECK(tlv_tree_reader_init(&reader, wire, sizeof wire, &format, frames, 4, 3, 3) == TLV_OK);
        state.calls = state.errors = 0;
        CHECK(tlv_query_program_visit(&reader, state.exec, event_visitor, &state, NULL) == TLV_OK);
        CHECK(state.calls == 2 && !state.errors);
    }
#endif
    return 0;
}
